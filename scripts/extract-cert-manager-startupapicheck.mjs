#!/usr/bin/env node

// Extracts the exact cert-manager startup API check hook objects from the
// locked chart archive. The output is canonicalized only at YAML document
// boundaries so a reviewed companion can name stable bytes without copying a
// hook by hand. It performs no network or cluster operation.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

import { check, parseDocs, sha256 } from "./lib/proof-common.mjs";

const chart = option("--chart");
const output = option("--output");
check(chart && output, "Usage: node scripts/extract-cert-manager-startupapicheck.mjs --chart <cert-manager-v1.21.0.tgz> --output <path>");

const expectedArtifact = "9c2c6fabf3cf8fe14dacb016f37c819b66bc2c79e8b7acde4573d45ec141fb97";
check(sha256(readFileSync(chart)) === expectedArtifact, "chart archive does not match the locked cert-manager v1.21.0 artifact");
const rendered = execFileSync("helm", ["template", "cert-manager", chart, "--namespace", "cert-manager", "--include-crds", "--skip-tests"], { encoding: "utf8" });
const docs = rendered
  .split(/^---\s*$/m)
  .map((doc) => doc.trim())
  .filter((doc) => doc.includes("helm.sh/hook:"));
check(docs.length === 4, `expected four startup hook documents, found ${docs.length}`);
const parsed = parseDocs(docs.join("\n---\n"));
check(parsed.every((doc) => doc.metadata?.annotations?.["helm.sh/hook"] === "post-install"), "extracted documents are not all post-install hooks");
check(parsed.some((doc) => doc.kind === "Job" && doc.metadata?.name === "cert-manager-startupapicheck"), "startup API check Job missing");
writeFileSync(output, `# Generated by scripts/extract-cert-manager-startupapicheck.mjs. Do not edit by hand.\n${docs.map((doc) => `---\n${doc}`).join("\n")}\n`);

function option(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : "";
}
