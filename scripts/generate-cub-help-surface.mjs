// Records the command paths and flags that the installed cub CLI and its
// plugins print in their own --help text, so the command-surface gates can
// check reader-facing sources without a CLI.
//
//   --write    runs `cub ... --help` on this machine and rewrites the snapshot.
//   --verify   (default) reads the committed snapshot and checks its shape. It
//              never runs cub, because CI installs an older CLI.
//
// Refresh the snapshot on a machine whose cub and plugins are the versions the
// site should document, then fix whatever the gates report.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { check, repoRoot } from "./lib/proof-common.mjs";
import { loadSnapshot, snapshotRelativePath, validateSnapshot } from "./lib/cub-command-surface.mjs";

const snapshotPath = join(repoRoot, snapshotRelativePath);
const mode = process.argv.includes("--write") ? "write" : "verify";

// Plugins whose commands the site documents. Each is walked from the command
// names `cub plugin list` reports for it.
const documentedPlugins = ["workshop", "installer", "helm", "sveltos-confighub", "kubara-confighub", "argo", "flux"];
const skippedSubcommands = new Set(["help", "completion"]);

if (mode === "write") {
  const snapshot = buildSnapshot();
  validateSnapshot(snapshot);
  writeFileSync(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(
    `wrote ${snapshotRelativePath}: cub ${snapshot.cub.version}, ${Object.keys(snapshot.commands).length} command path(s)`,
  );
} else {
  const snapshot = loadSnapshot();
  console.log(
    `verified ${snapshotRelativePath}: cub ${snapshot.cub.version}, ${Object.keys(snapshot.commands).length} command path(s), read offline`,
  );
}

function help(args) {
  try {
    return execFileSync("cub", [...args, "--help"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  } catch (error) {
    return `${error.stdout ?? ""}${error.stderr ?? ""}`;
  }
}

function buildSnapshot() {
  const versionText = execFileSync("cub", ["version"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const version = versionText.match(/Version:\s+(v[\d.]+)/)?.[1];
  const commit = versionText.match(/Commit:\s+([0-9a-f]{40})/)?.[1];
  check(Boolean(version), "could not read the cub client version");

  const installed = JSON.parse(
    execFileSync("cub", ["plugin", "list", "-o", "json"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }),
  );
  const commands = {};
  const rootHelp = help([]);
  const root = parseCobra(rootHelp);
  const globalFlags = [...new Set([...root.flags, "--help"])].sort();
  const coreGroups = root.subcommands.filter((name) => !skippedSubcommands.has(name));
  for (const group of coreGroups) walkCobra([group], `cub ${version}`, commands);

  const plugins = {};
  for (const name of documentedPlugins) {
    const plugin = installed.find((item) => item.name === name);
    check(Boolean(plugin), `plugin ${name} is not installed, so its help cannot be recorded`);
    plugins[name] = { version: plugin.version, commands: plugin.commands.map((item) => item.name).sort() };
    for (const command of plugin.commands) {
      const source = `plugin ${name} ${plugin.version}`;
      const text = help([command.name]);
      if (/^\s*Available Commands:|^Flags:/m.test(text)) walkCobra([command.name], source, commands);
      else recordUsageText(command.name, text, source, commands);
    }
  }

  return {
    schema: "cub-help-surface/v1",
    note:
      "Generated by scripts/generate-cub-help-surface.mjs --write from the --help text of the installed CLI. Do not edit by hand. Flags are the long flags each command's help lists; global flags are accepted everywhere.",
    cub: { version, commit },
    plugins,
    globalFlags,
    topLevel: [...coreGroups, ...Object.values(plugins).flatMap((plugin) => plugin.commands)].sort(),
    commands: Object.fromEntries(Object.entries(commands).sort(([a], [b]) => a.localeCompare(b))),
  };
}

function parseCobra(text) {
  const subcommands = [];
  const flags = [];
  let section = "";
  for (const line of text.split(/\r?\n/)) {
    if (/^\S.*:$/.test(line)) {
      section = line.replace(/:$/, "");
      continue;
    }
    if (/Commands$/.test(section)) {
      const match = line.match(/^ {2}([a-z][\w-]*)\s/);
      if (match) subcommands.push(match[1]);
    } else if (section === "Flags" || section === "Global Flags") {
      const match = line.match(/^\s+(?:-\w, )?(--[a-z][\w-]*)/);
      if (match) flags.push(match[1]);
    }
  }
  return { subcommands: [...new Set(subcommands)], flags: [...new Set(flags)].sort() };
}

function walkCobra(path, source, commands) {
  const parsed = parseCobra(help(path));
  const subcommands = parsed.subcommands.filter((name) => !skippedSubcommands.has(name)).sort();
  commands[path.join(" ")] = { source, style: "cobra", subcommands, flags: parsed.flags };
  for (const sub of subcommands) walkCobra([...path, sub], source, commands);
}

// The Workshop plugin prints one usage block for each group rather than cobra
// sections. A subcommand is a word that follows `cub <group>` on a usage line.
// Its flags are the long flags on its own usage lines and on the indented note
// lines under them; flags named in the prose below are recorded on the group.
function recordUsageText(group, text, source, commands) {
  const perSub = new Map();
  const groupFlags = new Set();
  const aliases = new Map();
  let current = null;
  let inUsage = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^Usage:/.test(line)) {
      inUsage = true;
      continue;
    }
    const usage = line.match(new RegExp(`^\\s+cub ${group} ([a-z][\\w-]*)(.*)$`));
    const flagsOnLine = [...line.matchAll(/(?:^|[\s[(|])(--[a-z][\w-]*)/g)].map((match) => match[1]);
    if (inUsage && usage) {
      current = usage[1];
      if (!perSub.has(current)) perSub.set(current, new Set());
      const oldName = line.match(/\(([a-z][\w-]*) is the old name for this\)/)?.[1];
      if (oldName) aliases.set(oldName, current);
      for (const flag of flagsOnLine) perSub.get(current).add(flag);
    } else if (inUsage && current && /^\s{4,}\S/.test(line)) {
      for (const flag of flagsOnLine) perSub.get(current).add(flag);
    } else {
      if (inUsage && line.trim() === "") current = null;
      for (const flag of flagsOnLine) groupFlags.add(flag);
    }
  }
  for (const [oldName, name] of aliases) perSub.set(oldName, perSub.get(name));
  commands[group] = { source, style: "usage-text", subcommands: [...perSub.keys()].sort(), flags: [...groupFlags].sort() };
  for (const [sub, flags] of perSub) {
    commands[`${group} ${sub}`] = {
      source,
      style: "usage-text",
      subcommands: [],
      flags: [...new Set([...flags, ...groupFlags])].sort(),
      ...(aliases.has(sub) ? { oldNameFor: aliases.get(sub) } : {}),
    };
  }
}
