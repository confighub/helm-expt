#!/usr/bin/env node
// Pilot switch-effect map: classify a chart's switches by RENDERING, not by
// hand. For each top-level feature toggle, render the chart flipped and diff
// the object set against the baseline. A switch that changes the object set is
// structural (base-variant territory); one that only changes field values is a
// data edit. The classification is evidence, not opinion: every row is a real
// render diff. Prototype on redis; the pattern templates across the catalog.
//
// Usage: node scripts/pilot-switch-effect-map.mjs [--chart redis]
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { repoRoot, write } from "./lib/proof-common.mjs";

const CHART = {
  ref: "oci://registry-1.docker.io/bitnamicharts/redis",
  version: "25.5.3",
  release: "redis",
  namespace: "redis",
  imageDigest: "sha256:6e7a020f1f6504698a7272c58783bdc2c23588c49febbae5aca1bb8dfa10af25",
};
const BASE_VALUES = `image:\n  digest: ${CHART.imageDigest}\nauth:\n  password: "confighub-redis-password"\n`;

// Top-level feature toggles extracted from the chart values, plus the primary
// architecture axis. The SET tested is enumerated; the VERDICT is rendered.
const SWITCHES = [
  { name: "architecture=standalone", values: "architecture: standalone\n" },
  { name: "sentinel.enabled", values: "sentinel:\n  enabled: true\n" },
  { name: "metrics.enabled", values: "metrics:\n  enabled: true\n" },
  { name: "tls.enabled", values: "tls:\n  enabled: true\n  autoGenerated:\n    enabled: true\n" },
  { name: "networkPolicy.enabled=false", values: "networkPolicy:\n  enabled: false\n" },
  { name: "serviceBindings.enabled", values: "serviceBindings:\n  enabled: true\n" },
  { name: "podSecurityPolicy.enabled", values: "podSecurityPolicy:\n  enabled: true\n" },
  { name: "volumePermissions.enabled", values: "volumePermissions:\n  enabled: true\n" },
  // Field-only controls: these should classify as field (no object-set change).
  { name: "replica.replicaCount=5", values: "replica:\n  replicaCount: 5\n" },
  { name: "master.count=2", values: "master:\n  count: 2\n" },
];

const tmp = mkdtempSync(join(tmpdir(), "pilot-switch-map-"));
try {
  const baseline = objectSet(renderHelm(BASE_VALUES));
  const rows = [];
  for (const sw of SWITCHES) {
    const objects = objectSet(renderHelm(BASE_VALUES + sw.values));
    const added = [...objects].filter((k) => !baseline.has(k));
    const removed = [...baseline].filter((k) => !objects.has(k));
    const kind = added.length || removed.length ? "structural" : "field";
    rows.push({ switch: sw.name, kind, baselineObjects: baseline.size, variantObjects: objects.size, added, removed });
    process.stdout.write(`${kind.padEnd(11)} ${sw.name}  (+${added.length} -${removed.length})\n`);
  }
  const structural = rows.filter((r) => r.kind === "structural");
  const outDir = join(repoRoot, "data", "pilot-switch-map");
  mkdirSync(outDir, { recursive: true });
  write(join(outDir, "redis.json"), `${JSON.stringify({ chart: `${CHART.ref}@${CHART.version}`, baselineObjects: baseline.size, rows }, null, 2)}\n`);
  write(join(outDir, "redis.md"), renderMarkdown(baseline.size, rows));
  console.log(`\n${structural.length}/${rows.length} switches are structural (change the object set); the rest are data edits.`);
  console.log(`Wrote data/pilot-switch-map/redis.{json,md}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

function renderHelm(valuesText) {
  const valuesPath = join(mkdtempSync(join(tmp, "v-")), "values.yaml");
  writeFileSync(valuesPath, valuesText);
  return execFileSync("helm", [
    "template", CHART.release, CHART.ref, "--version", CHART.version,
    "--namespace", CHART.namespace, "--values", valuesPath, "--kube-version", "1.30.0",
  ], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
}

// One object key per rendered document: kind|apiVersion|name.
function objectSet(yaml) {
  const set = new Set();
  for (const doc of yaml.split(/^---$/m)) {
    const kind = doc.match(/^kind:\s*(\S+)/m)?.[1];
    const api = doc.match(/^apiVersion:\s*(\S+)/m)?.[1];
    const name = doc.match(/^\s{2}name:\s*(\S+)/m)?.[1];
    if (kind && name) set.add(`${api}/${kind}/${name}`);
  }
  return set;
}

function renderMarkdown(baselineObjects, rows) {
  const structural = rows.filter((r) => r.kind === "structural");
  const field = rows.filter((r) => r.kind === "field");
  const lines = [
    "# Redis switch-effect map",
    "",
    "Classified by rendering, not by hand. Each switch below was flipped on the",
    `redis chart and the rendered object set compared against the baseline`,
    `(${baselineObjects} objects). A switch that changes the object set is`,
    "**structural** and belongs in a base variant. A switch that only changes",
    "field values is a **data edit** on a derived variant. The verdict is the",
    "diff, not an opinion.",
    "",
    "## Structural switches (change the object set)",
    "",
    "| Switch | Objects | Adds | Removes |",
    "| --- | --- | --- | --- |",
    ...structural.map((r) => `| \`${r.switch}\` | ${r.variantObjects} | ${r.added.map((a) => `\`${a}\``).join("<br>") || "-"} | ${r.removed.map((a) => `\`${a}\``).join("<br>") || "-"} |`),
    "",
    "## Data-edit switches (values only, no object-set change)",
    "",
    "| Switch | Objects |",
    "| --- | --- |",
    ...field.map((r) => `| \`${r.switch}\` | ${r.variantObjects} (unchanged set) |`),
    "",
    "## What this means",
    "",
    `Of ${rows.length} switches tested, ${structural.length} are structural and`,
    `${field.length} are data edits. Naming the structural axes as base variants`,
    "and leaving the rest as data edits avoids both the values-file sprawl and the",
    "combinatorial explosion. The switches were tested independently; a generated",
    "variant renders the actual combination and proves parity, so interaction",
    "effects are caught at generation, not assumed here.",
    "",
  ];
  return `${lines.join("\n")}\n`;
}
