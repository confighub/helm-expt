#!/usr/bin/env node
// Writes packages/<repo>/<chart>/upstream.yaml for every chart in the catalog:
// where the chart comes from, the name it is published and installed by, and
// every version packaged here. It is the same file, with the same first five
// fields, that each package in the confighub/packages repository keeps, with
// `type: helm` as that repository's design describes for chart-sourced
// packages. The upstream fields come from the newest version's recipe source
// lock, so the file never disagrees with what was rendered.
//
// The file sits beside the version directories, outside every package, so it
// is never bundled into one.
//
// Usage:
//   node scripts/generate-package-upstreams.mjs --generate
//   node scripts/generate-package-upstreams.mjs --verify
//   node scripts/generate-package-upstreams.mjs --self-test

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

import {
  GHCR_PACKAGES_REGISTRY,
  NAME_OVERRIDES,
  RESERVED_NAMES,
  catalogCharts,
  ghcrTag,
  nameProblems,
  shortNames,
} from "./lib/ghcr-packages.mjs";
import { check, readYaml, repoRoot } from "./lib/proof-common.mjs";

const mode = process.argv[2] ?? "--verify";
const indexPath = join(repoRoot, "data", "ghcr-packages", "packages.csv");

function upstreamText(entry) {
  const lock = readYaml(join(repoRoot, "recipes", entry.repo, entry.chart, entry.newest, "source-lock.yaml")).spec;
  check(lock?.sourceType === "HelmChart", `${entry.ref} ${entry.newest}: source lock is not a Helm chart`);
  check(lock.chart && lock.repositoryURL && lock.version, `${entry.ref} ${entry.newest}: source lock lacks chart, repositoryURL or version`);
  const lines = [
    "# Generated by scripts/generate-package-upstreams.mjs from the newest version's",
    "# recipe source lock. Do not edit; regenerate.",
    "#",
    "# Where this chart's packages come from. The nightly package update reads",
    "# repository and chart to find the newest upstream version.",
    "type: helm",
    `repository: ${lock.repositoryURL}`,
    `chart: ${lock.chart}`,
    "# The newest chart version packaged here.",
    `version: ${lock.chartVersion ?? lock.version}`,
    "# The name cub finds it by:",
    `#   cub package install ${entry.name} --space <space>`,
    `# which pulls oci://${GHCR_PACKAGES_REGISTRY}/${entry.name}:<tag>.`,
    // cub takes the highest vX.Y.Z tag when no version is named, and a package
    // revision's tag is not of that form.
    ...(lock.packageRevision
      ? [
          `# The newest package is revision ${lock.packageRevision} of ${lock.chartVersion}, which cub installs`,
          `# only when it is named: cub package install ${entry.name}:${ghcrTag(entry.newest)} --space <space>`,
        ]
      : []),
    `name: ${entry.name}`,
    "# Every version packaged here: its directory, and the tag it is published as.",
    "versions:",
    ...entry.versions.map((version) => `  - {directory: ${version}, tag: ${ghcrTag(version)}}`),
    "",
  ];
  return lines.join("\n");
}

function indexText(entries) {
  const rows = ["name,chart,repository,newest_tag,tags,reference"];
  for (const entry of entries) {
    const lock = readYaml(join(repoRoot, "recipes", entry.repo, entry.chart, entry.newest, "source-lock.yaml")).spec;
    const tags = entry.versions.map(ghcrTag);
    rows.push(
      [entry.name, entry.ref, lock.repositoryURL, tags.at(-1), tags.join(" "), `oci://${GHCR_PACKAGES_REGISTRY}/${entry.name}`].join(","),
    );
  }
  return `${rows.join("\n")}\n`;
}

function plan() {
  const charts = catalogCharts();
  const names = shortNames(charts);
  const problems = nameProblems(names);
  check(problems.length === 0, `package names:\n  ${problems.join("\n  ")}`);
  const entries = charts.map((chart) => ({ ...chart, name: names.get(chart.ref) }));
  const files = new Map(entries.map((entry) => [join(entry.dir, "upstream.yaml"), upstreamText(entry)]));
  files.set(indexPath, indexText([...entries].sort((a, b) => (a.name < b.name ? -1 : 1))));
  return { entries, files };
}

function generate() {
  const { entries, files } = plan();
  for (const [path, text] of files) writeFileSync(path, text);
  const versions = entries.reduce((sum, entry) => sum + entry.versions.length, 0);
  console.log(`wrote upstream.yaml for ${entries.length} charts (${versions} package versions) and ${relative(repoRoot, indexPath)}`);
}

function verify() {
  const { entries, files } = plan();
  const stale = [];
  for (const [path, text] of files) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) stale.push(relative(repoRoot, path));
  }
  check(stale.length === 0, `stale or missing; run node scripts/generate-package-upstreams.mjs --generate:\n  ${stale.join("\n  ")}`);
  console.log(`package upstreams verified: ${entries.length} charts, each with one name under ${GHCR_PACKAGES_REGISTRY}`);
}

function selfTest() {
  const charts = [
    { ref: "bitnami/nginx", repo: "bitnami", chart: "nginx" },
    { ref: "cloudpirates/nginx", repo: "cloudpirates", chart: "nginx" },
    { ref: "jetstack/cert-manager", repo: "jetstack", chart: "cert-manager" },
    { ref: "argo-cd/argo-cd", repo: "argo-cd", chart: "argo-cd" },
    { ref: "example/flux", repo: "example", chart: "flux" },
  ];
  const names = shortNames(charts);
  check(names.get("bitnami/nginx") === "bitnami-nginx", "a chart name two repositories share is qualified by repository");
  check(names.get("cloudpirates/nginx") === "cloudpirates-nginx", "both charts sharing a name are qualified");
  check(names.get("jetstack/cert-manager") === "cert-manager", "a unique chart keeps its own name");
  check(names.get("argo-cd/argo-cd") === NAME_OVERRIDES.get("argo-cd/argo-cd"), "an override wins");
  check(names.get("example/flux") === "example-flux", "a reserved name is never taken");
  check(nameProblems(names).length === 0, "the self-test names are valid");
  const clash = new Map([["a/x", "x"], ["b/x", "x"]]);
  check(nameProblems(clash).some((p) => p.includes("already the name")), "two charts on one name are refused");
  check(nameProblems(new Map([["a/b", "argocd"]])).some((p) => p.includes("another repository")), "a reserved name is refused");
  check(nameProblems(new Map([["a/b", "Bad_Name"]])).some((p) => p.includes("not a valid")), "an invalid OCI name is refused");
  check(ghcrTag("1.2.3") === "v1.2.3" && ghcrTag("v1.2.3") === "v1.2.3", "tags carry exactly one leading v");
  check(RESERVED_NAMES.has("argocd"), "argocd stays the packages repository's");
  console.log("package upstreams self-test passed");
}

if (mode === "--generate") generate();
else if (mode === "--verify") verify();
else if (mode === "--self-test") selfTest();
else {
  console.error("Usage: node scripts/generate-package-upstreams.mjs --generate|--verify|--self-test");
  process.exit(2);
}
