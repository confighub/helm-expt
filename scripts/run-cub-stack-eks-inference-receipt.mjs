// The keystone, spoken in the settled vocabulary: this driver runs
// `cub stack sandbox eks-inference` through the prototype and commits the
// receipt. The stack definition composes the eight digest-pinned certified
// bundles across three planes, every file is hash-verified against its
// receipt before parsing, and the certify step runs before the free render.
//
//   node scripts/run-cub-stack-eks-inference-receipt.mjs
//
// The capture hard-fails unless the stack certifies, all eight components
// resolve, and the one honest warning class, byte-identical shared CRDs
// carried by more than one chart inside the ACK component, is reported
// rather than hidden.

import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { check, repoRoot, write } from "./lib/proof-common.mjs";

const outRoot = join(repoRoot, "data", "eks-inf-replica", "stack-sandbox");
const result = execFileSync("node", [join(repoRoot, "scripts", "cub-stack.mjs"), "sandbox", "eks-inference"], { encoding: "utf8" });

check(result.includes("=> CERTIFIED"), "acceptance: the stack must certify");
check(result.includes("130 objects total"), "acceptance: the sandbox must render the full composition");
check(result.includes("held in ConfigHub, never applied"), "acceptance: the hub plane must be named as such");
check(result.includes("identical content; the last occurrence wins"), "acceptance: the shared-CRD duplication must be reported, not hidden");
const componentLines = result.split("\n").filter((line) => /^\s{6}\S.*: \d+/.test(line));
check(componentLines.length === 8, "acceptance: all eight components must resolve");

write(join(outRoot, "receipt.yaml"), [
  "apiVersion: evidence.confighub.com/v1alpha1",
  "kind: StackSandboxReceipt",
  "metadata:",
  "  name: cub-stack-eks-inference",
  "spec:",
  '  command: "node scripts/cub-stack.mjs sandbox eks-inference"',
  '  stackDefinition: "examples/cub-stack/stacks/eks-inference.yaml"',
  "  certified: true",
  "  transcript:",
  ...result.trimEnd().split("\n").map((line) => `    - "${line.replaceAll('"', "'")}"`),
  "  boundaries:",
  '    - "A certified sandbox is a free look at the whole composition, not a deployment; the governed organization rebuild and the delivery lanes carry those proofs."',
  '    - "The prototype certify runs four checks; the full eight-check composition verdict is the committed one it cross-references."',
].join("\n") + "\n");
write(join(outRoot, "summary.md"), `# The keystone speaks the vocabulary

<!-- Generated by scripts/run-cub-stack-eks-inference-receipt.mjs. Do not edit by hand. -->

The sentence the ladder promises now runs: \`cub stack sandbox eks-inference\`. The stack definition composes the eight digest-pinned certified bundles of the EKS inference platform across three planes, every file hash-verified against its receipt before a single object parses. The certify step passes with one honest warning, the shared ACK CRDs carried byte-identically by more than one chart inside one component, where the last occurrence wins at apply. The free render then lays out all 130 objects, with the hub plane named as held in ConfigHub and never applied.

\`cub stack certify eks-inference\` runs the gate alone, \`cub stack upload eks-inference\` points at the proven organization rebuild, and the full eight-check composition verdict stays the committed judgment this run cross-references. The transcript is in [receipt.yaml](./receipt.yaml).

The staged plan is [eks-inf-replica-plan.md](../../../docs/planning/eks-inf-replica-plan.md).
`);
console.log("receipt written: certified, 8 components, 130 objects, the duplication warning reported");
