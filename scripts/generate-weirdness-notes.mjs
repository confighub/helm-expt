import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { check, readYaml, relativeRepo, write } from "./lib/proof-common.mjs";
import { catalogDerivedPath, recipeRoots } from "./lib/catalog-derived-views.mjs";

const mode = process.argv[2] ?? "--generate";

if (mode === "--generate") {
  const notes = eligibleRecipeRoots().map(buildNote);
  for (const note of notes) write(note.path, note.markdown);
  console.log(`wrote ${notes.length} weirdness and mitigation note(s)`);
} else if (mode === "--verify") {
  const notes = eligibleRecipeRoots().map(buildNote);
  check(notes.length === 20, `expected 20 weirdness notes for supported top-20 recipes, found ${notes.length}`);
  for (const note of notes) {
    check(existsSync(note.path), `missing ${relativeRepo(note.path)}; run npm run catalog:weirdness`);
    check(readFileSync(note.path, "utf8") === note.markdown, `${relativeRepo(note.path)} is stale`);
  }
  console.log("verified weirdness and mitigation notes");
} else {
  console.log(`Usage:
  node scripts/generate-weirdness-notes.mjs --generate
  node scripts/generate-weirdness-notes.mjs --verify`);
}

function eligibleRecipeRoots() {
  return recipeRoots()
    .filter((root) => {
      const status = readYaml(catalogDerivedPath(root, "catalog-status.yaml"));
      return status.spec?.status === "catalog-supported";
    })
    .sort();
}

function buildNote(root) {
  const status = readYaml(catalogDerivedPath(root, "catalog-status.yaml"));
  const dossier = readYaml(join(root, "chart-dossier.yaml"));
  const controlPoints = readYaml(join(root, "control-points.yaml"));
  const recipe = readYaml(join(root, "recipe.yaml"));
  const chart = status.spec?.chart ?? dossier.spec?.chart ?? recipe.spec?.chartRef?.name ?? "unknown";
  const version = status.spec?.version ?? dossier.spec?.version ?? recipe.spec?.chartRef?.version ?? "unknown";
  const supportedVariants = status.spec?.supportedVariants ?? [];
  const candidateVariants = status.spec?.candidateVariants ?? [];
  const variants = supportedVariants.length ? supportedVariants : candidateVariants;
  const points = controlPoints.spec?.points ?? [];
  const dossierNotes = dossier.spec?.maintainedNotes ?? [];
  const statusNotes = status.spec?.notes ?? [];
  const controlPointNames = [...new Set([...(dossier.spec?.knownControlPoints ?? []), ...points.map((point) => point.category)])].sort();
  const markdown = `<!-- Generated by npm run catalog:weirdness. Do not edit by hand. -->

# ${chart} ${version} Weirdness And Mitigations

This note records the Helm pain surfaced during catalog review and where the
current ConfigHub/cub installer proof absorbs it.

## Support Boundary

| Field | Value |
| --- | --- |
| Catalog status | ${status.spec?.status ?? "unknown"} |
| Support level | ${status.spec?.supportLevel ?? "unknown"} |
| Supported scopes | ${listInline(status.spec?.supportedScopes)} |
| Production readiness | ${status.spec?.productionReadiness ?? "unknown"} |
| Variants in this note | ${listInline(variants)} |

Production support is not implied by this file. A chart can be supported for
local proof/demo use while still needing accepted scan, gate, lifecycle, and
operating-policy dispositions plus a final target-scoped support decision.

## Chart Notes

${bulletList(dossierNotes)}

## Catalog Mitigations

${bulletList(statusNotes)}

## Control Points

| Control point | Status | Mitigation / evidence |
| --- | --- | --- |
${points.map((point) => `| ${escapeCell(point.category)} | ${escapeCell(point.status ?? "recorded")} | ${escapeCell(point.note ?? point.evidence ?? point.policy ?? point.object ?? "recorded in control-points.yaml")} |`).join("\n")}

## Control Point Index

${bulletList(controlPointNames)}

## Proof Links

- Catalog map: [CATALOG.md](CATALOG.md)
- Machine index: [artifact-index.yaml](artifact-index.yaml)
- Helm plan: [helm-plan.yaml](helm-plan.yaml)
- Control points: [control-points.yaml](control-points.yaml)
- Chart dossier: [chart-dossier.yaml](chart-dossier.yaml)
`;

  return { path: catalogDerivedPath(root, "weirdness-and-mitigations.md"), markdown };
}

function listInline(values) {
  if (!values?.length) return "none";
  return values.join(", ");
}

function bulletList(values) {
  if (!values?.length) return "- none";
  return values.map((value) => `- ${value}`).join("\n");
}

function escapeCell(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
}
