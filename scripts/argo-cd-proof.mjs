// Argo CD proof.
//
// Chart-specific declaration only; all generate/verify/package machinery lives in
// scripts/lib/proof-kit.mjs. CLI surface unchanged.

import { runProofCli } from "./lib/proof-kit.mjs";
import { identityFor } from "./lib/proof-common.mjs";

const supportedChartVersion = "9.5.15";
const chartVersion = process.env.HELM_EXPT_CHART_VERSION ?? supportedChartVersion;

const chart = {
  repository: "argo-cd",
  repositoryURL: "https://argoproj.github.io/argo-helm",
  name: "argo-cd",
  version: chartVersion,
  releaseName: "argo-cd",
  namespace: "argocd",
  kubeVersion: "1.30.0",
};

const versionExpectations = {
  "9.5.15": { defaultObjects: 49, noCrdsObjects: 46 },
  "9.5.17": { defaultObjects: 49, noCrdsObjects: 46 },
  "10.1.3": { defaultObjects: 55, noCrdsObjects: 52 },
  "10.2.1": { defaultObjects: 55, noCrdsObjects: 52 },
};
const expected = versionExpectations[chart.version];
if (!expected) throw new Error(`argo-cd ${chart.version} needs reviewed version-specific assertions`);

const argoCDCRDs = [
  "applications.argoproj.io",
  "applicationsets.argoproj.io",
  "appprojects.argoproj.io",
];

const argoCDGeneratedSecrets = [
  {
    namespace: chart.namespace,
    name: "argocd-redis",
    keys: ["auth"],
    purpose: "Redis auth Secret normally generated by the chart secret-init hook; config-only delivery lanes stage it explicitly",
    deliveryLanes: ["cubInstallerApply", "configHubKubectlApply", "configHubOciArgo"],
  },
];

const variants = [
  {
    name: "default",
    base: "default",
    displayName: "default",
    valuesFile: "effective-values.yaml",
    valuesText: "",
    valuesSummary: "chart defaults",
    expectedObjectCount: expected.defaultObjects,
    expectedCRDCount: 3,
    expectedSecretCount: 2,
    targetFacts: {
      requiredSecrets: argoCDGeneratedSecrets,
    },
    targetFactNote: "includes the three Argo CD CRDs, built-in Redis, and generated chart Secrets; config-only lanes stage the Redis auth Secret explicitly",
  },
  {
    name: "no-crds",
    base: "no-crds",
    displayName: "CRDs disabled",
    valuesFile: "effective-values-no-crds.yaml",
    valuesText: `crds:
  install: false
`,
    valuesSummary: "Argo CD CRDs disabled",
    expectedObjectCount: expected.noCrdsObjects,
    expectedCRDCount: 0,
    expectedSecretCount: 2,
    targetFacts: {
      requiredSecrets: argoCDGeneratedSecrets,
      requiredCRDs: argoCDCRDs.map((name) => ({
        name,
        sourceVariant: "default",
        purpose: "Argo CD CRD managed outside this no-crds base",
        deliveryLanes: ["regularHelm", "cubInstallerApply", "configHubKubectlApply", "configHubOciArgo"],
      })),
    },
    targetFactNote:
      "omits the three Argo CD CRDs while preserving the control-plane workloads, built-in Redis, Secrets, and RBAC objects; target clusters must already provide the Argo CD CRDs",
  },
];

const scanPolicy = {
  scanner: "helm-expt-local-rendered-object-scan",
  version: "0.1.0",
  rules: [
    { id: "mutable-image-tag", severity: "high", description: "Container image must use an immutable or non-latest tag." },
    { id: "service-selector-has-workload-match", severity: "high", description: "Service selector must match a rendered workload pod template." },
    { id: "workload-service-account-exists", severity: "high", description: "Workload serviceAccountName must reference a rendered ServiceAccount." },
    { id: "helm-hook-lifecycle-policy", severity: "medium", description: "Helm hook resources need explicit lifecycle policy." },
    { id: "dependency-lock-review", severity: "medium", description: "Disabled chart dependencies still need lock and provenance review." },
    { id: "generated-secret-ownership", severity: "medium", description: "Rendered Secrets need explicit ownership and observation policy." },
    { id: "crd-upgrade-policy", severity: "medium", description: "CRDs need explicit readiness, ordering, schema, and upgrade policy." },
    { id: "cluster-rbac-review", severity: "medium", description: "Cluster-scoped RBAC needs explicit review before production." },
    { id: "stateful-workload-review", severity: "medium", description: "Stateful workloads need storage, upgrade, and rollback policy." },
    { id: "extension-slot-review", severity: "medium", description: "tpl/raw extension slots need provenance and scan coverage." },
  ],
};

runProofCli({
  chart,
  variants,
  scanPolicy,
  expectedDependencyCount: 1,
  recordChartLockDigest: true,
  valueModel: {
    checkedValues: [
      { path: "crds.install", variant: "default", disposition: "crds-included", reason: "chart defaults render the three Argo CD CRDs" },
      { path: "crds.install", variant: "no-crds", disposition: "crds-excluded", reason: "omits CRDs from the rendered revision for clusters that manage CRDs separately" },
      { path: "crds.*", variant: "all", disposition: "crd-selection-controls", reason: "controls Argo CD CRD rendering and lifecycle policy" },
      { path: "extraObjects", variant: "all", disposition: "empty-extension-slot", reason: "chart exposes a tpl-powered extension slot; promoted variants keep it empty" },
      { path: "redis-ha.enabled", variant: "all", disposition: "disabled-dependency", reason: "chart declares and locks the redis-ha dependency, but promoted variants keep it disabled" },
      { path: "redisSecretInit.enabled", variant: "all", disposition: "secret-initializer-enabled", reason: "Argo CD renders argocd-secret and a Redis secret initializer path that must be treated as generated/operational state" },
      { path: "configs.*", variant: "all", disposition: "config-extension-surface", reason: "Argo CD configuration, repositories, credentials, and notifications are managed as explicit variant/config inputs" },
    ],
  },
  controlPoints: [
    { category: "source-lock", status: "handled", evidence: "source-lock.yaml" },
    { category: "dependency-lock", status: "handled", evidence: "dependency-lock.yaml", note: "chart declares redis-ha dependency; promoted variants keep it disabled but lock its metadata." },
    { category: "capability-profile", status: "handled", kubeVersion: chart.kubeVersion, note: "Kubernetes API and version branches are bound to the named Kubernetes capability profile." },
    {
      category: "crd-policy",
      status: "variant-controlled-and-target-fact",
      variants: { default: 3, "no-crds": 0 },
      note: "CRDs are ordinary rendered objects in the default variant and required target facts for the no-crds variant.",
    },
    { category: "hook-policy", status: "handled-for-render", policy: "no-hooks", note: "Chart source contains Helm hooks; the proof render excludes hooks and lifecycle policy must handle them before production." },
    {
      category: "hook-generated-secret",
      status: "target-fact-for-config-only-lanes",
      object: "v1|Secret|argocd|argocd-redis",
      note: "Regular Helm creates this Secret via the chart secret-init path; config-only lanes stage it explicitly before workloads start.",
    },
    { category: "cluster-rbac", status: "scan-and-review", evidence: "scan receipts" },
    { category: "stateful-workload", status: "scan-and-review", object: "apps/v1|StatefulSet|argocd|argo-cd-argocd-application-controller" },
    { category: "tpl", status: "controlled-by-empty-defaults", note: "extraObjects uses tpl; promoted variants do not set that value." },
    { category: "gitops-handoff", status: "documented", note: "Argo CD is itself a GitOps controller; ConfigHub OCI publication remains the default handoff pattern for this project." },
    { category: "installer-support-object", status: "handled", object: "v1|Namespace||argocd" },
  ],
  dossier: {
    maintainedNotes: [
      "Default chart renders the three Argo CD CRDs because crds.install defaults to true.",
      "no-crds variant omits CRDs for clusters that manage CRDs separately and records those CRDs as target facts.",
      "Chart declares a redis-ha dependency that remains disabled in promoted variants but is recorded in dependency-lock.yaml.",
      "Chart source contains Helm hook annotations; the rendered proof excludes hooks and keeps lifecycle policy explicit.",
      "The argocd-redis auth Secret is generated by Helm's secret-init path and staged explicitly for config-only delivery lanes.",
      "Argo CD renders Secrets for application state and notifications; ownership and freshness need operation receipts.",
      "The application controller is a StatefulSet and needs storage/upgrade/rollback policy even without PVC templates.",
      "extraObjects is a tpl-powered extension slot; promoted variants keep it empty.",
    ],
    knownControlPoints: [
      "capability-profile",
      "crd-lifecycle-policy",
      "dependency-lock",
      "hook-lifecycle-policy",
      "hook-generated-secret",
      "generated-secret-ownership",
      "stateful-workload-policy",
      "gitops-handoff",
      "cluster-rbac-scan",
      "tpl-extension-slot",
    ],
  },
  plan: {
    status: "usable-with-controls",
    scanGate: "warn-production-blocked",
    nextAction: "publish only after CRD lifecycle/upgrade policy, hook lifecycle policy, generated Secret ownership, dependency lock review, StatefulSet policy, GitOps handoff policy, and cluster RBAC review are satisfied",
  },
  readme: {
    intro: "This is the promoted proof slice for the Argo CD public Helm chart.",
    proves: [
      "regular Helm output is preserved by `cub installer setup`, plus the explained Namespace support object;",
      "default and no-crds variants make CRD ownership explicit;",
      "generated Secrets, built-in Redis, StatefulSet behavior, dependency metadata, and cluster RBAC are visible as scan/gate findings;",
      "extraObjects is a tpl-powered extension slot and remains empty in promoted variants;",
      "Argo CD can be installed as a chart while the ConfigHub OCI handoff remains the default delivery path for other catalog entries.",
    ],
  },
  installGate: (variant) => ({
    decision: "warn",
    reasons: [
      `Helm equivalence passed for ${variant.name}`,
      "CRD install/upgrade behavior needs explicit lifecycle policy before production",
      "Helm hook behavior needs explicit lifecycle policy before production",
      "The argocd-redis hook-generated Secret is staged explicitly for config-only delivery lanes",
      "Argo CD generated/operational Secrets need ownership and observation policy",
      "Argo CD StatefulSet behavior needs storage, upgrade, and rollback policy",
      "Cluster-scoped RBAC needs production review",
      "GitOps handoff should use the ConfigHub OCI path for this project",
      variant.targetFactNote,
    ],
  }),
  scanExtra(docs) {
    const findings = [];
    for (const doc of docs.filter((item) => item.kind === "CustomResourceDefinition")) {
      findings.push({
        id: `crd-upgrade-policy:${identityFor(doc)}`,
        rule: "crd-upgrade-policy",
        severity: "medium",
        object: identityFor(doc),
        message: "CRD readiness, ordering, schema validation, and upgrade compatibility require explicit policy",
      });
    }
    for (const doc of docs.filter((item) => ["argocd-secret", "argocd-notifications-secret"].includes(item.metadata?.name))) {
      findings.push({
        id: `generated-secret-ownership:${identityFor(doc)}`,
        rule: "generated-secret-ownership",
        severity: "medium",
        object: identityFor(doc),
        message: "Argo CD Secret content and ownership must be explicit before production promotion",
      });
    }
    findings.push({
      id: "dependency-lock-review:redis-ha",
      rule: "dependency-lock-review",
      severity: "medium",
      object: "dependency|redis-ha|4.34.11",
      message: "Disabled redis-ha dependency is locked and should remain disabled unless selected by a variant",
    });
    findings.push({
      id: "helm-hook-lifecycle-policy:source",
      rule: "helm-hook-lifecycle-policy",
      severity: "medium",
      object: "source|helm-hooks",
      message: "Chart source contains Helm hooks; rendered proof excludes hooks and production needs lifecycle policy",
    });
    findings.push({
      id: "extension-slot-review:extraObjects",
      rule: "extension-slot-review",
      severity: "medium",
      object: "values|extraObjects",
      message: "extraObjects is a tpl-powered extension slot and must be scanned when populated",
    });
    for (const doc of docs.filter((item) => item.kind === "StatefulSet")) {
      findings.push({
        id: `stateful-workload-review:${identityFor(doc)}`,
        rule: "stateful-workload-review",
        severity: "medium",
        object: identityFor(doc),
        message: "Stateful workload requires storage, upgrade, and rollback policy",
      });
    }
    for (const doc of docs.filter((item) => ["ClusterRole", "ClusterRoleBinding"].includes(item.kind))) {
      findings.push({
        id: `cluster-rbac-review:${identityFor(doc)}`,
        rule: "cluster-rbac-review",
        severity: "medium",
        object: identityFor(doc),
        message: "Cluster-scoped RBAC requires production review",
      });
    }
    return findings;
  },
  verifyExtra({ dependencyLock, controlPoints, perVariant, check }) {
    check(dependencyLock.spec.dependencies?.[0]?.name === "redis-ha", "argo-cd dependency name mismatch");
    check(controlPoints.spec.points?.some((point) => point.category === "capability-profile"), "capability-profile control point missing");
    check(controlPoints.spec.points?.some((point) => point.category === "crd-policy"), "crd-policy control point missing");
    check(controlPoints.spec.points?.some((point) => point.category === "hook-policy"), "hook-policy control point missing");
    check(controlPoints.spec.points?.some((point) => point.category === "hook-generated-secret"), "hook-generated-secret control point missing");
    check(controlPoints.spec.points?.some((point) => point.category === "stateful-workload"), "stateful-workload control point missing");
    check(controlPoints.spec.points?.some((point) => point.category === "gitops-handoff"), "gitops-handoff control point missing");

    for (const variant of variants) {
      const { identities, scan } = perVariant.get(variant.name);
      const crdIdentities = identities.filter((identity) => identity.startsWith("apiextensions.k8s.io/v1|CustomResourceDefinition|"));
      const secretIdentities = identities.filter((identity) => identity.startsWith("v1|Secret|"));
      check(crdIdentities.length === variant.expectedCRDCount, `${variant.name} CRD count mismatch`);
      check(secretIdentities.length === variant.expectedSecretCount, `${variant.name} Secret count mismatch`);
      check(identities.includes("apps/v1|Deployment|argocd|argo-cd-argocd-server"), `${variant.name} server Deployment missing`);
      check(identities.includes("apps/v1|Deployment|argocd|argo-cd-argocd-repo-server"), `${variant.name} repo-server Deployment missing`);
      check(identities.includes("apps/v1|Deployment|argocd|argo-cd-argocd-applicationset-controller"), `${variant.name} applicationset Deployment missing`);
      check(identities.includes("apps/v1|Deployment|argocd|argo-cd-argocd-redis"), `${variant.name} redis Deployment missing`);
      check(identities.includes("apps/v1|StatefulSet|argocd|argo-cd-argocd-application-controller"), `${variant.name} application-controller StatefulSet missing`);
      check(identities.includes("v1|Service|argocd|argo-cd-argocd-server"), `${variant.name} server Service missing`);
      check(identities.includes("v1|Service|argocd|argo-cd-argocd-redis"), `${variant.name} redis Service missing`);
      check(identities.includes("v1|Secret|argocd|argocd-secret"), `${variant.name} argocd-secret missing`);
      check(identities.includes("v1|Secret|argocd|argocd-notifications-secret"), `${variant.name} notifications Secret missing`);
      if (variant.name === "default") {
        const requiredCRDs = [
          ...argoCDCRDs.map((name) => `apiextensions.k8s.io/v1|CustomResourceDefinition||${name}`),
        ];
        for (const identity of requiredCRDs) check(identities.includes(identity), `missing CRD ${identity}`);
      }
      if (variant.name === "no-crds") {
        check(!crdIdentities.length, "no-crds must not render CRDs");
      }
      check(scan.spec.findingCounts.medium >= 3, `${variant.name} scan must flag CRD/hook/dependency/stateful/RBAC review`);
    }
  },
});
